#!/usr/bin/env bash
# Install dsh-proxy and a systemd unit that starts it at boot.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PREFIX="${PREFIX:-/usr/local}"
CONF_DIR="${CONF_DIR:-/etc/dsh-proxy}"
UNIT_DIR="${UNIT_DIR:-/etc/systemd/system}"
TARGET_USER="${SUDO_USER:-$(id -un)}"
LISTEN="0.0.0.0:8080"
DSH_PORT=0
ENABLE=1
FORCE=0

usage() {
	cat <<'EOF'
Usage: sudo ./scripts/install.sh [options]

  --user NAME       service user (default: $SUDO_USER, else current user)
  --listen IP:PORT  listen address written to the generated config
                    (default: 0.0.0.0:8080)
  --dsh-port PORT   dsh listen port; 0 = OS-assigned free port (default: 0)
  --no-enable       install files but do not enable/start the service
  --force           overwrite an existing /etc/dsh-proxy/dsh-proxy.conf
  -h, --help        show this help
EOF
}

while [[ $# -gt 0 ]]; do
	case "$1" in
	--user)
		TARGET_USER="${2:?--user needs a name}"
		shift 2
		;;
	--listen)
		LISTEN="${2:?--listen needs IP:PORT}"
		shift 2
		;;
	--dsh-port)
		DSH_PORT="${2:?--dsh-port needs a port}"
		if ! [[ "$DSH_PORT" =~ ^[0-9]+$ ]] || [[ "$DSH_PORT" -gt 65535 ]]; then
			echo "invalid --dsh-port: $DSH_PORT" >&2
			exit 2
		fi
		shift 2
		;;
	--no-enable)
		ENABLE=0
		shift
		;;
	--force)
		FORCE=1
		shift
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		echo "unknown option: $1" >&2
		usage >&2
		exit 2
		;;
	esac
done

if [[ "${EUID}" -ne 0 ]]; then
	echo "run this with sudo (it writes /etc and /usr/local/bin)" >&2
	exit 1
fi
if ! getent passwd "$TARGET_USER" >/dev/null; then
	echo "unknown user: $TARGET_USER" >&2
	exit 1
fi
if [[ "$TARGET_USER" == "root" ]]; then
	echo "refusing to install a root-run service: dsh must run as a normal user." >&2
	echo "pass --user <name> (for example: --user lbh)." >&2
	exit 1
fi

TARGET_GROUP="$(id -gn "$TARGET_USER")"
TARGET_HOME="$(getent passwd "$TARGET_USER" | cut -d: -f6)"

find_dsh() {
	local candidate
	candidate="$(command -v dsh 2>/dev/null || true)"
	if [[ -n "$candidate" ]]; then
		printf '%s\n' "$candidate"
		return 0
	fi
	for candidate in "$TARGET_HOME/.local/bin/dsh" \
		"$TARGET_HOME/bin/dsh" \
		"$TARGET_HOME/.npm-global/bin/dsh"; do
		if [[ -x "$candidate" ]]; then
			printf '%s\n' "$candidate"
			return 0
		fi
	done
	if [[ -d "$TARGET_HOME/.npm/_npx" ]]; then
		find "$TARGET_HOME/.npm/_npx" \
			-path '*/node_modules/.bin/dsh' \( -type l -o -type f \) \
			-printf '%T@ %p\n' 2>/dev/null |
			sort -nr | head -n 1 | cut -d' ' -f2-
	fi
}

DSH_BIN="$(find_dsh || true)"
if [[ -n "$DSH_BIN" ]]; then
	DSH_CMD="$DSH_BIN web --no-open"
	DSH_PATH="$(dirname "$DSH_BIN"):/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
else
	if ! command -v npx >/dev/null 2>&1; then
		echo "could not find dsh or npx; install DSH first" >&2
		exit 1
	fi
	DSH_CMD="npx @deepseek-ai/dsh web --no-open"
	DSH_PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
	echo "warning: dsh was not found on PATH; generated DSH_CMD uses npx" >&2
fi

echo "building $ROOT/dsh-proxy"
if [[ "$TARGET_USER" != "root" ]] && command -v runuser >/dev/null 2>&1; then
	if ! runuser -u "$TARGET_USER" -- make -C "$ROOT"; then
		echo "build as $TARGET_USER failed; retrying as root" >&2
		make -C "$ROOT"
	fi
else
	make -C "$ROOT"
fi

install -Dm0755 "$ROOT/dsh-proxy" "$PREFIX/bin/dsh-proxy"
install -d "$CONF_DIR"

if [[ -f "$CONF_DIR/dsh-proxy.conf" && "$FORCE" -ne 1 ]]; then
	echo "keeping existing $CONF_DIR/dsh-proxy.conf (use --force to replace)"
	echo "  check that DSH_CMD points at: $DSH_BIN"
else
	if [[ -f "$CONF_DIR/dsh-proxy.conf" ]]; then
		cp "$CONF_DIR/dsh-proxy.conf" \
			"$CONF_DIR/dsh-proxy.conf.bak.$(date +%s)"
	fi
	{
		echo "# Generated by dsh-proxy scripts/install.sh"
		echo "# See packaging/dsh-proxy.conf for all keys and warnings."
		echo "LISTEN=$LISTEN"
		echo "DSH_CMD=$DSH_CMD"
		echo "DSH_PORT=$DSH_PORT"
		echo "TOKEN_TIMEOUT=180"
		echo "RESTART_DELAY=5"
		echo "COOKIE_REFRESH=21600"
		echo "AUTO_YES=1"
		echo "LOG_LEVEL=info"
	} >"$CONF_DIR/dsh-proxy.conf"
	chmod 0644 "$CONF_DIR/dsh-proxy.conf"
fi

escape_sed() {
	printf '%s' "$1" | sed -e 's/[&|\\]/\\&/g'
}

sed \
	-e "s|@DSH_PROXY_USER@|$(escape_sed "$TARGET_USER")|g" \
	-e "s|@DSH_PROXY_GROUP@|$(escape_sed "$TARGET_GROUP")|g" \
	-e "s|@DSH_PROXY_HOME@|$(escape_sed "$TARGET_HOME")|g" \
	-e "s|@DSH_PROXY_PATH@|$(escape_sed "$DSH_PATH")|g" \
	"$ROOT/packaging/dsh-proxy.service.in" >"$UNIT_DIR/dsh-proxy.service"
chmod 0644 "$UNIT_DIR/dsh-proxy.service"

systemctl daemon-reload
if [[ "$ENABLE" -eq 1 ]]; then
	systemctl enable --now dsh-proxy
	echo
	systemctl --no-pager --lines=5 status dsh-proxy || true
else
	echo
	echo "installed; start with: systemctl enable --now dsh-proxy"
fi

cat <<EOF

Installed:
  binary  $PREFIX/bin/dsh-proxy
  config  $CONF_DIR/dsh-proxy.conf
  unit    $UNIT_DIR/dsh-proxy.service
  user    $TARGET_USER ($TARGET_HOME; never root)
  dsh     $DSH_CMD
  port    $DSH_PORT (0 = OS-assigned free port, discovered from dsh output)

Logs:
  journalctl -u dsh-proxy -f

SECURITY: the proxy injects the DSH credential into every request it accepts.
Anyone who can reach $LISTEN has full DSH access (including shell execution).
Bind it to a trusted LAN/VPN address and firewall the port; never expose it to
the public internet. The upstream connection is plain HTTP.
EOF
