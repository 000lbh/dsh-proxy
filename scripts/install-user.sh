#!/usr/bin/env bash
# Install dsh-proxy as a systemd --user service. Run WITHOUT sudo.
#
# The proxy and the dsh child run as your user. For boot without logging in,
# enable linger once (as root):  sudo loginctl enable-linger "$USER"
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HOME_DIR="${HOME:-}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME_DIR/.config}"
BIN_DIR="$HOME_DIR/.local/bin"
CONF_DIR="$CONFIG_HOME/dsh-proxy"
UNIT_DIR="$CONFIG_HOME/systemd/user"
LISTEN="0.0.0.0:8080"
DSH_PORT=0
ENABLE=1
FORCE=0
USER_NAME="$(id -un)"

usage() {
	cat <<'USAGE'
Usage: ./scripts/install-user.sh [options]    (do NOT use sudo)

  --listen IP:PORT   proxy listen address (default: 0.0.0.0:8080)
  --dsh-port PORT    dsh listen port; 0 = let the OS pick a free port
                     (default: 0, recommended)
  --no-enable        install files but do not enable/start the user unit
  --force            overwrite an existing config
  -h, --help         show this help
USAGE
}

while [[ $# -gt 0 ]]; do
	case "$1" in
	--listen)
		LISTEN="${2:?--listen needs IP:PORT}"
		shift 2
		;;
	--dsh-port)
		DSH_PORT="${2:?--dsh-port needs a port}"
		if ! [[ "$DSH_PORT" =~ ^[0-9]+$ ]] || [[ "$DSH_PORT" -gt 65535 ]]; then
			echo "invalid --dsh-port: $DSH_PORT" >&2
			exit 2
		fi
		shift 2
		;;
	--no-enable)
		ENABLE=0
		shift
		;;
	--force)
		FORCE=1
		shift
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		echo "unknown option: $1" >&2
		usage >&2
		exit 2
		;;
	esac
done

if [[ "${EUID}" -eq 0 ]]; then
	echo "do NOT run this with sudo: the service must run as your user." >&2
	echo "Run it as $USER_NAME; only 'loginctl enable-linger' needs root." >&2
	exit 1
fi
if [[ -z "$HOME_DIR" ]]; then
	echo "HOME is not set" >&2
	exit 1
fi
if [[ "$HOME_DIR" != /* ]]; then
	echo "HOME must be an absolute path: $HOME_DIR" >&2
	exit 1
fi
if [[ "$CONFIG_HOME" != /* ]]; then
	CONFIG_HOME="$HOME_DIR/$CONFIG_HOME"
fi
BIN_DIR="$HOME_DIR/.local/bin"
CONF_DIR="$CONFIG_HOME/dsh-proxy"
UNIT_DIR="$CONFIG_HOME/systemd/user"
if ! command -v systemctl >/dev/null 2>&1; then
	echo "systemctl not found; this installer targets systemd" >&2
	exit 1
fi

find_dsh() {
	local candidate
	candidate="$(command -v dsh 2>/dev/null || true)"
	if [[ -n "$candidate" ]]; then
		printf '%s\n' "$candidate"
		return 0
	fi
	for candidate in "$HOME_DIR/.local/bin/dsh" \
		"$HOME_DIR/bin/dsh" \
		"$HOME_DIR/.npm-global/bin/dsh"; do
		if [[ -x "$candidate" ]]; then
			printf '%s\n' "$candidate"
			return 0
		fi
	done
	if [[ -d "$HOME_DIR/.npm/_npx" ]]; then
		find "$HOME_DIR/.npm/_npx" \
			-path '*/node_modules/.bin/dsh' \( -type l -o -type f \) \
			-printf '%T@ %p\n' 2>/dev/null |
			sort -nr | head -n 1 | cut -d' ' -f2-
	fi
}

DSH_BIN="$(find_dsh || true)"
if [[ -n "$DSH_BIN" ]]; then
	DSH_CMD="$DSH_BIN web --no-open"
	DSH_PATH="$(dirname "$DSH_BIN"):/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
else
	if ! command -v npx >/dev/null 2>&1; then
		echo "could not find dsh or npx; install DSH first" >&2
		exit 1
	fi
	DSH_CMD="npx @deepseek-ai/dsh web --no-open"
	DSH_PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
	echo "warning: dsh was not found on PATH; generated DSH_CMD uses npx" >&2
fi

echo "building $ROOT/dsh-proxy"
make -C "$ROOT"

install -Dm0755 "$ROOT/dsh-proxy" "$BIN_DIR/dsh-proxy"
install -d "$CONF_DIR" "$UNIT_DIR"

if [[ -f "$CONF_DIR/dsh-proxy.conf" && "$FORCE" -ne 1 ]]; then
	echo "keeping existing $CONF_DIR/dsh-proxy.conf (use --force to replace)"
	echo "  detected dsh: $DSH_BIN"
else
	if [[ -f "$CONF_DIR/dsh-proxy.conf" ]]; then
		cp "$CONF_DIR/dsh-proxy.conf" \
			"$CONF_DIR/dsh-proxy.conf.bak.$(date +%s)"
	fi
	{
		echo "# Generated by dsh-proxy scripts/install-user.sh"
		echo "# See packaging/dsh-proxy.conf for all keys and warnings."
		echo "LISTEN=$LISTEN"
		echo "DSH_CMD=$DSH_CMD"
		echo "DSH_PORT=$DSH_PORT"
		echo "TOKEN_TIMEOUT=180"
		echo "RESTART_DELAY=5"
		echo "COOKIE_REFRESH=21600"
		echo "AUTO_YES=1"
		echo "LOG_LEVEL=info"
	} >"$CONF_DIR/dsh-proxy.conf"
	chmod 0644 "$CONF_DIR/dsh-proxy.conf"
fi

escape_sed() {
	printf '%s' "$1" | sed -e 's/[&|\\]/\\&/g'
}

sed \
	-e "s|@DSH_PROXY_HOME@|$(escape_sed "$HOME_DIR")|g" \
	-e "s|@DSH_PROXY_CONFIG@|$(escape_sed "$CONF_DIR/dsh-proxy.conf")|g" \
	-e "s|@DSH_PROXY_PATH@|$(escape_sed "$DSH_PATH")|g" \
	"$ROOT/packaging/dsh-proxy.user.service.in" \
	>"$UNIT_DIR/dsh-proxy.service"
chmod 0644 "$UNIT_DIR/dsh-proxy.service"

USER_MANAGER=1
if ! systemctl --user daemon-reload; then
	USER_MANAGER=0
	echo "warning: 'systemctl --user' is not available in this session." >&2
	echo "files are installed; log in to the user manager and run:" >&2
	echo "  systemctl --user daemon-reload" >&2
	echo "  systemctl --user enable --now dsh-proxy" >&2
fi
if [[ "$USER_MANAGER" -eq 1 && "$ENABLE" -eq 1 ]]; then
	systemctl --user enable --now dsh-proxy || true
	systemctl --user --no-pager --lines=5 status dsh-proxy || true
elif [[ "$ENABLE" -eq 0 ]]; then
	echo "installed; start with: systemctl --user enable --now dsh-proxy"
fi

LINGER="$(loginctl show-user "$USER_NAME" -p Linger --value 2>/dev/null || true)"
cat <<EOF

Installed as user $USER_NAME (never root):
  binary  $BIN_DIR/dsh-proxy
  config  $CONF_DIR/dsh-proxy.conf
  unit    $UNIT_DIR/dsh-proxy.service
  dsh     $DSH_CMD
  port    $DSH_PORT (0 means the OS picks a free port; the proxy reads it from dsh output)

For boot without logging in, enable linger once (needs root):
  sudo loginctl enable-linger $USER_NAME

Logs:
  journalctl --user -u dsh-proxy -f

If the service is not running yet:
  systemctl --user daemon-reload
  systemctl --user enable --now dsh-proxy

SECURITY: the proxy injects the DSH credential into every request it accepts.
Anyone who can reach $LISTEN has full DSH access (including shell execution).
Bind it to a trusted LAN/VPN address and firewall the port; never expose it to
the public internet. The upstream connection is plain HTTP.
EOF

if [[ "$LINGER" != "yes" ]]; then
	echo
	echo "NOTE: linger is currently '${LINGER:-unknown}'; without it the user service starts at login, not at boot."
fi
